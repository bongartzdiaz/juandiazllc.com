/** HTML-escape user-supplied strings (org name, project titles, etc.).
 *  Template authors should pass user data through this — the shell
 *  doesn't trust upstream input. */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

/** Wrap inner template HTML in the branded shell. */
export function renderShell(opts: RenderShellOpts): string {
  const safeOrgName = escapeHtml(opts.orgName)
  const safeTitle = escapeHtml(opts.title)
  const safeSubtitle = opts.subtitle ? escapeHtml(opts.subtitle) : null
  const safeFooter = escapeHtml(opts.footerText)
  const logoBlock = opts.orgLogoUrl
    ? `<img class="report-header__logo" src="${escapeHtml(opts.orgLogoUrl)}" alt="${safeOrgName}" />`
    : `<div class="report-header__brand">DEUS</div>`

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>${safeTitle} — ${safeOrgName}</title>
<style>${SHELL_CSS}</style>
</head>
<body>
  <div class="report-shell">
    <header class="report-header">
      <div>
        <h1 class="report-title">${safeTitle}</h1>
        ${safeSubtitle ? `<p class="report-subtitle">${safeSubtitle}</p>` : ''}
        <div class="report-header__org">${safeOrgName}</div>
      </div>
      <div>${logoBlock}</div>
    </header>
    <main>
      ${opts.innerHtml}
    </main>
    <footer class="report-footer">
      <span>${safeFooter}</span>
      <span>${opts.generatedAt.toISOString().slice(0, 10)}</span>
    </footer>
  </div>
</body>
</html>`
}
