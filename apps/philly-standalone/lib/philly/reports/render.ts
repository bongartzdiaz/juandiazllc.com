/* Branded HTML shell for generated reports.
   ──────────────────────────────────────────────────────────────────
   Wraps a template's inner HTML in a professional, DEUS-branded
   header + footer. Operators can re-style by editing this file
   without touching individual templates.

   ## Design choices

   - Single-file CSS (inline <style>) so the HTML is portable — print
     to PDF, email as attachment, paste into a Notion page, all work.
   - System font stack — never depends on a CDN-hosted webfont
     (operators print without internet sometimes; offline-safe matters).
   - Brand colour kept to one accent line (no DEUS-blue everywhere) —
     reports look authoritative without screaming "marketing collateral".
   - Footer carries a confidentiality marker + generation timestamp +
     org name. Required by some EU enterprise procurement reviewers.
   - The `logoUrl` slot supports the org's own logo (per-tenant). Default
     to the DEUS wordmark when null.
   --------------------------------------------------------------- */

export interface RenderShellOpts {
  title: string
  orgName: string
  orgLogoUrl?: string | null
  generatedAt: Date
  /** Inner template HTML — assumed already escaped. */
  innerHtml: string
  /** Footer copy translated to the active locale.
   *  e.g. "Generated by DEUS · Confidential · {date}". */
  footerText: string
  /** Optional subtitle under the title, e.g. "Q2 2026 · 12 projects". */
  subtitle?: string
}

